function argValue(name, fallback) {
  const prefix = `--${name}=`;
  const found = process.argv.find((argument) => argument.startsWith(prefix));
  return found ? found.slice(prefix.length) : fallback;
}

function normalizeCard(card) {
  const phaseLabel = phaseLabels[card.phase];
  if (!phaseLabel) throw new Error(`未知阶段：${card.phase}`);
  for (const key of ["stableId", "title", "summary", "appliesWhen", "risk", "lessonTitle"]) {
    if (!String(card[key] ?? "").trim()) throw new Error(`${card.stableId || card.title} 缺少 ${key}`);
  }
  if (!Number.isFinite(card.lessonNo)) throw new Error(`${card.stableId} 缺少 lessonNo`);
  if (!Number.isFinite(card.pageStart) || !Number.isFinite(card.pageEnd)) {
    throw new Error(`${card.stableId} 缺少页码`);
  }
  if (card.summary.length > 180) throw new Error(`${card.stableId} summary 超过 180 字`);
  return {
    stableId: card.stableId,
    reviewStatus: "approved",
    phase: card.phase,
    title: card.title,
    summary: card.summary,
    appliesWhen: card.appliesWhen,
    risk: card.risk,
    tags: [...new Set([phaseLabel, ...card.tags])],
    engineCorrelations: card.engineCorrelations,
    source: {
      label: "赵鑫鑫棋理三部曲",
      book: bookByPhase[card.phase],
      lessonNo: card.lessonNo,
      lessonTitle: card.lessonTitle,
      pageStart: card.pageStart,
      pageEnd: card.pageEnd,
      review: "已按课题结构批量种子确认",
    },
  };
}

